class Decl:
    """A generated Java type (class, enum, union interface or holder)."""

    def __init__(self, kind, name, parent, package, loc, description=None):
        self.kind = kind  # class | enum | union | holder
        self.name = name
        self.parent = parent
        self.package = package
        self.loc = loc
        self.description = description
        self.children = []
        self.props = []
        self.extra = None  # JType of additional properties, or None if closed
        self.enum_values = []
        self.variants = []  # Decls for unions
        self.interfaces = []  # union Decls this class implements
        self.deprecated = False
        self.done = False

    def path(self):
        names = []
        d = self
        while d is not None:
            names.append(d.name)
            d = d.parent
        return list(reversed(names))

    def top(self):
        d = self
        while d.parent is not None:
            d = d.parent
        return d

    def qualified(self):
        return ".".join(self.path())

    def fqn(self):
        return f"{self.package}.{self.qualified()}"

    def child_names(self):
        return {c.name for c in self.children}

    def all_names(self):
        out = {self.name}
        for c in self.children:
            out |= c.all_names()
        return out


