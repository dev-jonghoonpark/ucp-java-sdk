class Generator:
    def __init__(self, schemas, base_package):
        self.s = schemas
        self.base_package = base_package
        self.by_loc = {}
        self.tops = []
        self.in_progress = set()

    # ---- schema shape helpers ---------------------------------------------

    def flatten(self, loc, seen=None):
        """Merges allOf branches (resolving $refs) into a single schema node.

        Returns (node, file) where node has no allOf; if/then branches are
        dropped. A node that is just a $ref with annotations is followed.
        """
        seen = seen or set()
        node = loc.node
        if not isinstance(node, dict):
            return node
        out = {k: v for k, v in node.items() if k != "allOf"}
        if "$ref" in out and ("properties" in out or "allOf" in node):
            ref = out.pop("$ref")
            target = self.s.resolve(ref, loc.file)
            if target.key not in seen:
                base = self.rebase(self.flatten(target, seen | {target.key}),
                                   target.file, loc.file)
                out = deep_merge(base, out)
        merged = {}
        for branch in node.get("allOf", []):
            if not isinstance(branch, dict):
                continue
            if any(k in branch for k in ("if", "then", "else", "not")):
                continue
            if "$ref" in branch:
                target = self.s.resolve(branch["$ref"], loc.file)
                if target.key in seen:
                    continue
                part = self.flatten(target, seen | {target.key})
                part = self.rebase(part, target.file, loc.file)
                extras = {k: v for k, v in branch.items() if k != "$ref"}
                if extras:
                    part = deep_merge(part, extras)
            else:
                part = self.flatten(Loc(loc.file, loc.pointer, branch), seen)
            # Metadata of included schemas must not override the includer's.
            for k in ("title", "description", "$id", "$schema", "name"):
                part.pop(k, None)
            merged = deep_merge(merged, part)
        if merged:
            out = deep_merge(merged, out)
        return out

    def rebase(self, node, from_file, to_file):
        """Rewrites relative $refs in node so they resolve from to_file."""
        if from_file == to_file:
            return copy.deepcopy(node)

        def fix(n):
            if isinstance(n, dict):
                r = {}
                for k, v in n.items():
                    if k == "$ref" and isinstance(v, str):
                        path, _, frag = v.partition("#")
                        target = normalize_path(
                            (Path(from_file).parent / path).as_posix()
                        ) if path else from_file
                        r[k] = self.relpath(target, to_file) + (
                            "#" + frag if frag or "#" in v else "")
                    else:
                        r[k] = fix(v)
                return r
            if isinstance(n, list):
                return [fix(x) for x in n]
            return n

        return fix(node)

    @staticmethod
    def relpath(target, from_file):
        import os.path

        base = Path(from_file).parent.as_posix() or "."
        rel = os.path.relpath(target, base)
        return rel.replace(os.sep, "/")

    def deref(self, loc):
        """Follows a bare $ref (one carrying only annotations)."""
        seen = set()
        while (isinstance(loc.node, dict) and "$ref" in loc.node
               and "properties" not in loc.node and "allOf" not in loc.node
               and not any(k in loc.node for k in SCHEMA_ROOT_KEYS)):
            target = self.s.resolve(loc.node["$ref"], loc.file)
            if target.key in seen:
                break
            seen.add(target.key)
            loc = target
        return loc

    def classify(self, loc):
        """Returns the shape of the schema at loc.

        One of: object, map, array, enum, union, primitive, any.
        """
        node = self.flatten(loc)
        if not isinstance(node, dict):
            return "any", node
        if "$ref" in node:
            target = self.deref(Loc(loc.file, loc.pointer, node))
            if target.key != loc.key:
                return self.classify(target)
        branches = self.union_branches(loc.file, node)
        if branches is not None and "properties" not in node:
            return "union", node
        types = node.get("type")
        if isinstance(types, list):
            non_null = [t for t in types if t != "null"]
            types = non_null[0] if len(non_null) == 1 else None
            if types is None:
                return "any", node
        if "properties" in node or (branches is not None):
            return "object", node
        if types == "object":
            return "map", node
        if types == "array":
            return "array", node
        if "enum" in node and all(isinstance(v, str) for v in node["enum"]) and (
            types in (None, "string")
        ):
            return "enum", node
        if types in ("string", "integer", "number", "boolean"):
            return "primitive", node
        if "const" in node:
            return "primitive", node
        return "any", node

    def union_branches(self, file, node):
        """Returns union branches if node is a real union, else None.

        Branches that carry no $ref, allOf or title only restate constraints on
        the enclosing object; those make the node an object, not a union.
        """
        for key in SCHEMA_ROOT_KEYS:
            branches = node.get(key)
            if not isinstance(branches, list):
                continue
            real = [b for b in branches if isinstance(b, dict) and (
                "$ref" in b or "allOf" in b or "title" in b
                or b.get("type") not in (None, "object"))]
            if real:
                return branches
        return None

    # ---- type resolution ----------------------------------------------------

    def package_for(self, file):
        parent = Path(file).parent.as_posix()
        if parent in ("", "."):
            return self.base_package
        return self.base_package + "." + ".".join(
            re.sub(r"[^a-z0-9_]", "_", p.lower()) for p in parent.split("/"))

    def unique_child_name(self, parent, wanted):
        taken = parent.child_names() if parent else set()
        enclosing = set(parent.path()) if parent else set()
        name = wanted
        if name in RESERVED_TYPE_NAMES:
            name += "Type"
        if name in enclosing:
            name += "Def"
        base, i = name, 2
        while name in taken or name in enclosing:
            name = f"{base}{i}"
            i += 1
        return name

    def decl_for(self, loc, kind, wanted, parent):
        """Returns the Decl for the schema at loc, creating it if needed.

        Named locations (file roots and $defs) are owned by their file's
        top-level type; inline locations nest under `parent`.
        """
        named = loc.pointer == "" or re.fullmatch(r"/\$defs/[^/]+", loc.pointer)
        if loc.key in self.by_loc:
            return self.by_loc[loc.key]
        if named:
            if loc.pointer == "":
                parent = None
                name = pascal(Path(loc.file).stem)
            else:
                top = self.top_for_file(loc.file)
                parent = top
                name = self.unique_child_name(
                    top, pascal(loc.pointer.rsplit("/", 1)[1]))
        else:
            name = self.unique_child_name(parent, wanted)
        package = self.package_for(loc.file)
        node = self.flatten(loc) if isinstance(loc.node, dict) else {}
        d = Decl(kind, name, parent, package, loc,
                 node.get("description") or node.get("title"))
        d.deprecated = bool(node.get("deprecated"))
        if parent is None:
            self.tops.append(d)
        else:
            parent.children.append(d)
        self.by_loc[loc.key] = d
        return d

    def unique_top_name(self, package, wanted):
        """Returns a top-level name free in package.

        Checks every file-root type the package will contain (known up front
        from the schema files), not only those generated so far.
        """
        taken = {t.name for t in self.tops if t.package == package}
        taken |= {pascal(Path(f).stem) for f in self.s.docs
                  if self.package_for(f) == package}
        name, i = wanted, 2
        while name in taken:
            name = f"{wanted}{i}"
            i += 1
        return name

    def top_for_file(self, file):
        loc = Loc(file, "", self.s.docs[file])
        if loc.key in self.by_loc:
            return self.by_loc[loc.key]
        shape, _ = self.classify(loc)
        kind = {"object": "class", "enum": "enum", "union": "union",
                "map": "map"}.get(shape, "holder")
        d = self.decl_for(loc, kind, None, None)
        if kind == "holder":
            d.done = True
        return d

    def jtype(self, loc, parent, hint):
        """Maps the schema at loc to a JType, generating nested types as needed.

        `parent` is the Decl inline types nest under, `hint` the name an inline
        type gets.
        """
        node = loc.node
        if isinstance(node, bool) or node == {}:
            return JType("Object")
        if isinstance(node, dict) and "$ref" in node and not (
            "properties" in node or "allOf" in node
            or any(k in node for k in SCHEMA_ROOT_KEYS)
        ):
            target = self.s.resolve(node["$ref"], loc.file)
            return self.jtype(target, parent, hint)

        shape, flat = self.classify(loc)
        named = loc.pointer == "" or re.fullmatch(r"/\$defs/[^/]+", loc.pointer)
        if named and loc.pointer != "" and loc.key not in self.by_loc:
            # Make sure the owning top-level type exists first.
            self.top_for_file(loc.file)

        if shape == "object":
            d = self.decl_for(loc, "class", hint, parent)
            self.build_class(d)
            return JType(decl=d)
        if shape == "enum":
            d = self.decl_for(loc, "enum", hint, parent)
            if not d.done:
                d.done = True
                d.enum_values = list(flat["enum"])
            return JType(decl=d)
        if shape == "union":
            return self.union_type(loc, flat, parent, hint)
        if shape == "array":
            items = flat.get("items")
            if items is None:
                return JType("List", args=[JType("Object")], imports=["java.util.List"])
            item_loc = Loc(loc.file, loc.pointer + "/items", items)
            item_hint = singular(hint) if hint else "Item"
            if named and loc.pointer == "":
                top = self.top_for_file(loc.file)
                return JType("List", args=[self.jtype(item_loc, top, singular(top.name))],
                             imports=["java.util.List"])
            return JType("List", args=[self.jtype(item_loc, parent, item_hint)],
                         imports=["java.util.List"])
        if shape == "map" and named:
            d = self.decl_for(loc, "map", hint, parent)
            if not d.done:
                d.done = True
                ap = flat.get("additionalProperties", True)
                if isinstance(ap, dict) and ap:
                    d.extra = self.jtype(
                        Loc(loc.file, loc.pointer + "/additionalProperties", ap),
                        d, "Value")
                else:
                    d.extra = JType("Object")
            return JType(decl=d)
        if shape == "map":
            ap = flat.get("additionalProperties", True)
            if isinstance(ap, dict) and ap:
                value = self.jtype(
                    Loc(loc.file, loc.pointer + "/additionalProperties", ap),
                    parent, hint + "Value" if hint else "Value")
            else:
                value = JType("Object")
            return JType("Map", args=[JType("String"), value],
                         imports=["java.util.Map"])
        if shape == "primitive":
            return self.primitive(flat)
        return JType("JsonNode", imports=["com.fasterxml.jackson.databind.JsonNode"])

    @staticmethod
    def primitive(node):
        t = node.get("type")
        if isinstance(t, list):
            t = next((x for x in t if x != "null"), None)
        if t is None and "const" in node:
            c = node["const"]
            t = ("boolean" if isinstance(c, bool) else "integer" if isinstance(c, int)
                 else "number" if isinstance(c, float) else "string")
        if t == "string":
            fmt = node.get("format")
            if fmt == "date-time":
                return JType("OffsetDateTime", imports=["java.time.OffsetDateTime"])
            if fmt == "date":
                return JType("LocalDate", imports=["java.time.LocalDate"])
            if fmt == "uri":
                return JType("URI", imports=["java.net.URI"])
            return JType("String")
        if t == "integer":
            return JType("Long")
        if t == "number":
            return JType("Double")
        if t == "boolean":
            return JType("Boolean")
        return JType("Object")

    def union_type(self, loc, flat, parent, hint):
        branches = self.union_branches(loc.file, flat) or []
        variant_types = []
        nullable_only = True
        for i, b in enumerate(branches):
            if isinstance(b, dict) and b.get("type") == "null" and len(b) == 1:
                continue
            nullable_only = False
            bloc = Loc(loc.file, f"{loc.pointer}/{'oneOf' if 'oneOf' in flat else 'anyOf'}/{i}", b)
            variant_types.append((bloc, b))
        # Are all branches object-shaped? Then it is a real (interface) union.
        object_branches = []
        for bloc, b in variant_types:
            target = self.deref(bloc)
            shape, _ = self.classify(target)
            if shape not in ("object", "union"):
                object_branches = None
                break
            object_branches.append(target)
        if not object_branches:
            # Primitive / mixed union. Collapse if all branches agree.
            if not nullable_only:
                mapped = []
                for bloc, b in variant_types:
                    target = self.deref(bloc)
                    shape, f = self.classify(target)
                    if shape != "primitive":
                        mapped = None
                        break
                    mapped.append(self.primitive(f).simple)
                if mapped and len(set(mapped)) == 1:
                    return self.primitive(self.classify(self.deref(variant_types[0][0]))[1])
            return JType("JsonNode", imports=["com.fasterxml.jackson.databind.JsonNode"])

        d = self.decl_for(loc, "union", hint, parent)
        if d.done:
            return JType(decl=d)
        d.done = True
        variants = []
        for i, target in enumerate(object_branches):
            if target.pointer == "" or re.fullmatch(r"/\$defs/[^/]+", target.pointer):
                vt = self.jtype(target, d, None)
            else:
                name = self.variant_name(target, i)
                vt = self.jtype(target, d, name)
            vd = vt.decl
            if vd.kind == "union":
                variants.extend(vd.variants)
            else:
                variants.append(vd)
        for vd in variants:
            if d not in vd.interfaces:
                vd.interfaces.append(d)
        d.variants = variants
        # A class cannot implement an interface nested inside itself; hoist
        # such a union to a top-level type of its own.
        ancestors = set()
        p = d.parent
        while p is not None:
            ancestors.add(id(p))
            p = p.parent
        if any(id(v) in ancestors for v in variants):
            d.parent.children.remove(d)
            d.name = self.unique_top_name(d.package, "".join(d.path()))
            d.parent = None
            self.tops.append(d)
        return JType(decl=d)

    def variant_name(self, loc, index):
        node = loc.node
        if isinstance(node, dict):
            if node.get("title"):
                return pascal(node["title"])
            for b in node.get("allOf", []):
                if isinstance(b, dict) and "$ref" in b:
                    ref = b["$ref"]
                    frag = ref.split("#", 1)[1] if "#" in ref else ""
                    if frag:
                        return pascal(frag.rsplit("/", 1)[1])
                    return pascal(Path(ref).stem)
        return f"Variant{index + 1}"

    # ---- class construction -------------------------------------------------

    def build_class(self, d):
        if d.done or d.loc.key in self.in_progress:
            return
        self.in_progress.add(d.loc.key)
        d.done = True
        loc = d.loc
        node = self.flatten(loc)
        # Merge object-constraint branches (anyOf of required sets, or
        # property-redeclaring branches) into the object.
        props = dict(node.get("properties", {}))
        for key in SCHEMA_ROOT_KEYS:
            for b in node.get(key, []) or []:
                if isinstance(b, dict) and "$ref" not in b:
                    bf = self.flatten(Loc(loc.file, loc.pointer, b))
                    for pname, pschema in bf.get("properties", {}).items():
                        props.setdefault(pname, pschema)
        required = set(node.get("required", []))
        used = set()
        for pname, pschema in props.items():
            ploc = Loc(loc.file, f"{loc.pointer}/properties/{pname}", pschema)
            java_name = camel(pname)
            base, i = java_name, 2
            while java_name in used or java_name == "additionalProperties":
                java_name = f"{base}{i}"
                i += 1
            used.add(java_name)
            pflat = self.flatten(ploc) if isinstance(pschema, dict) else {}
            desc = pflat.get("description") if isinstance(pflat, dict) else None
            if isinstance(pschema, dict) and "$ref" in pschema and not desc:
                try:
                    desc = self.flatten(self.deref(ploc)).get("description")
                except Exception:
                    desc = None
            jt = self.jtype(ploc, d, pascal(pname))
            const = pflat.get("const") if isinstance(pflat, dict) else None
            default = pflat.get("default") if isinstance(pflat, dict) else None
            d.props.append(Prop(pname, java_name, jt, pname in required, desc,
                                const if isinstance(const, str) else None,
                                default,
                                bool(pflat.get("deprecated")) if isinstance(pflat, dict) else False))
        ap = node.get("additionalProperties", True)
        if ap is False:
            d.extra = None
        elif isinstance(ap, dict) and ap:
            d.extra = self.jtype(Loc(loc.file, loc.pointer + "/additionalProperties", ap),
                                 d, "AdditionalProperty")
        else:
            d.extra = JType("Object")
        self.in_progress.discard(loc.key)

    # ---- driver ---------------------------------------------------------------

    def run(self):
        for file in sorted(self.s.docs):
            top = self.top_for_file(file)
            loc = Loc(file, "", self.s.docs[file])
            if top.kind != "holder":
                self.jtype(loc, None, None)
            for name in self.s.docs[file].get("$defs", {}):
                dloc = Loc(file, f"/$defs/{name}", self.s.docs[file]["$defs"][name])
                if self.deref(dloc).key != dloc.key:
                    # A bare $ref: reuse the target's model.
                    target = self.deref(dloc)
                    self.jtype(target, None, None)
                    ALIASES[f"{file}#/$defs/{name}"] = target
                    continue
                shape, _ = self.classify(dloc)
                if shape in ("object", "enum", "union", "map"):
                    self.jtype(dloc, top, pascal(name))
        # A holder only exists to carry nested types.
        self.tops = [t for t in self.tops if t.kind != "holder" or t.children]


