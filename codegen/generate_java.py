"""Generates Jackson-annotated Java models from preprocessed UCP JSON schemas.

Input is the schema tree after preprocess_schemas.py has run (request
variants such as checkout_create_request.json already materialized, local
allOf chains flattened). Mapping rules:

* Every schema file maps to one top-level Java type named after the file
  stem: a class for objects, an enum for string enums, an interface for
  unions, and a non-instantiable holder class for files that only carry
  ``$defs``. Primitive schemas (a string with a pattern, an integer amount)
  produce no type; references to them resolve to the Java primitive wrapper.
* ``$defs`` entries and inline objects/enums become static nested types of
  the type that encloses them, so names never collide across files.
* ``allOf`` is flattened (later branches deep-merge over earlier ones);
  ``if``/``then``/``not``/``contains`` are left to the bundled JSON Schema
  validator.
* ``oneOf``/``anyOf`` whose branches reference object schemas become a Java
  interface implemented by every variant, deserialized by
  ``dev.ucp.sdk.json.UnionDeserializer``. Branches that only add
  ``required`` constraints are merged into the object instead. Unions of
  primitives fall back to ``JsonNode``.

Usage: generate_java.py <schema_dir> <java_src_root> <base_package> <ucp_version>
"""

