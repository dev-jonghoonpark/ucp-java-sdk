class Renderer:
    def __init__(self, top, all_tops, docs):
        self.top = top
        self.docs = docs
        self.imports = set()
        self.local_names = top.all_names()
        self.same_package = {t.name for t in all_tops if t.package == top.package}
        self.imported_simple = {}

    def ref(self, jt):
        if jt.decl is not None:
            d = jt.decl
            dtop = d.top()
            q = d.qualified()
            if dtop is self.top:
                return q
            if dtop.package == self.top.package:
                if dtop.name in self.local_names:
                    return d.fqn()
                return q
            # Different package: import the top-level type unless that would
            # shadow or clash.
            if (dtop.name in self.local_names or dtop.name in self.same_package
                    or self.imported_simple.get(dtop.name, dtop.fqn()) != dtop.fqn()):
                return d.fqn()
            self.imported_simple[dtop.name] = dtop.fqn()
            self.imports.add(dtop.fqn())
            return q
        self.imports |= jt.imports
        if jt.args:
            return f"{jt.simple}<{', '.join(self.ref(a) for a in jt.args)}>"
        return jt.simple

    def render(self):
        body = self.render_decl(self.top, 0)
        imports = sorted(self.imports)
        out = [HEADER, f"package {self.top.package};\n"]
        if imports:
            out.append("\n".join(f"import {i};" for i in imports) + "\n")
        out.append(body)
        return "\n".join(out)

    def schema_annotation(self, d, indent):
        """Returns the @UcpSchema line when d's pointer exists in its file."""
        node = self.docs[d.loc.file]
        for part in [p for p in d.loc.pointer.split("/") if p]:
            if isinstance(node, list) and part.isdigit() and int(part) < len(node):
                node = node[int(part)]
            elif isinstance(node, dict) and part in node:
                node = node[part]
            else:
                return ""
        self.imports.add("dev.ucp.sdk.UcpSchema")
        loc = d.loc.file + ("#" + d.loc.pointer if d.loc.pointer else "")
        REGISTRY.setdefault(loc, d.fqn())
        return f"{' ' * indent}@UcpSchema({java_string(loc)})\n"

    def render_decl(self, d, indent):
        if d.kind == "class":
            return self.render_class(d, indent)
        if d.kind == "enum":
            return self.render_enum(d, indent)
        if d.kind == "map":
            return self.render_map(d, indent)
        if d.kind == "union":
            return self.render_union(d, indent)
        return self.render_holder(d, indent)

    def modifiers(self, d, kind):
        mods = ["public"]
        if d.parent is not None and kind in ("class",) and d.parent.kind != "union":
            mods.append("static")
        if kind == "holder":
            mods.append("final")
        return " ".join(mods)

    def children(self, d, indent):
        defs = list(self.docs[d.loc.file].get("$defs", {})) if d.parent is None else []

        def order(c):
            m = re.fullmatch(r"/\$defs/([^/]+)", c.loc.pointer)
            if m and m.group(1) in defs and c.loc.file == d.loc.file:
                return (0, defs.index(m.group(1)))
            return (1, 0)

        kids = sorted(d.children, key=order)
        return "".join("\n" + self.render_decl(c, indent) for c in kids)

    def render_holder(self, d, indent):
        pad = " " * indent
        out = javadoc(d.description or f"Definitions from {d.loc.file}.", indent)
        static = " static" if d.parent is not None else ""
        out += f"{pad}public{static} final class {d.name} {{\n"
        out += f"{pad}    private {d.name}() {{}}\n"
        out += self.children(d, indent + 4)
        out += f"{pad}}}\n"
        return out

    def render_map(self, d, indent):
        self.imports.add("java.util.LinkedHashMap")
        pad = " " * indent
        static = " static" if d.parent is not None and d.parent.kind != "union" else ""
        out = javadoc(d.description, indent)
        out += self.schema_annotation(d, indent)
        out += f"{pad}public{static} class {d.name} extends LinkedHashMap<String, {self.ref(d.extra)}> {{\n"
        out += f"{pad}    private static final long serialVersionUID = 1L;\n"
        out += self.children(d, indent + 4)
        out += f"{pad}}}\n"
        return out

    def render_enum(self, d, indent):
        self.imports |= {"com.fasterxml.jackson.annotation.JsonValue"}
        pad = " " * indent
        out = javadoc(d.description, indent)
        out += f"{pad}public enum {d.name} {{\n"
        names, used = [], set()
        for v in d.enum_values:
            n, i = constant(v), 2
            while n in used:
                n = f"{constant(v)}_{i}"
                i += 1
            used.add(n)
            names.append((n, v))
        out += ",\n".join(f"{pad}    {n}({java_string(v)})" for n, v in names) + ";\n\n"
        out += f"{pad}    private final String value;\n\n"
        out += f"{pad}    {d.name}(String value) {{\n{pad}        this.value = value;\n{pad}    }}\n\n"
        out += f"{pad}    @JsonValue\n{pad}    public String value() {{\n{pad}        return value;\n{pad}    }}\n\n"
        # No @JsonCreator: Jackson maps values through @JsonValue, which keeps
        # READ_UNKNOWN_ENUM_VALUES_AS_NULL and problem handlers working (see
        # UcpJson.newLenientObjectMapper).
        out += f"{pad}    /**\n{pad}     * Returns the constant for a wire value.\n{pad}     *\n"
        out += f"{pad}     * @param value the wire value\n{pad}     * @return the constant\n"
        out += f"{pad}     * @throws IllegalArgumentException if the value is not defined\n{pad}     */\n"
        out += f"{pad}    public static {d.name} fromValue(String value) {{\n"
        out += f"{pad}        for ({d.name} v : values()) {{\n"
        out += f"{pad}            if (v.value.equals(value)) {{\n{pad}                return v;\n{pad}            }}\n{pad}        }}\n"
        out += f"{pad}        throw new IllegalArgumentException(\"Unknown {d.name} value: \" + value);\n{pad}    }}\n\n"
        out += f"{pad}    @Override\n{pad}    public String toString() {{\n{pad}        return value;\n{pad}    }}\n"
        out += f"{pad}}}\n"
        return out

    def render_union(self, d, indent):
        self.imports |= {"com.fasterxml.jackson.databind.annotation.JsonDeserialize",
                         "dev.ucp.sdk.json.UnionDeserializer", "java.util.List",
                         "java.util.Map"}
        pad = " " * indent
        variants = ", ".join(f"{{@link {self.ref(JType(decl=v))}}}" for v in d.variants)
        out = javadoc(d.description, indent, [f"One of: {variants}."])
        out += self.schema_annotation(d, indent)
        out += f"{pad}@JsonDeserialize(using = {d.name}.Deserializer.class)\n"
        out += f"{pad}public interface {d.name} {{\n"
        out += f"{pad}    /** Picks the variant whose required properties and constants match. */\n"
        out += f"{pad}    final class Deserializer extends UnionDeserializer<{d.name}> {{\n"
        out += f"{pad}        private static final long serialVersionUID = 1L;\n\n"
        out += f"{pad}        public Deserializer() {{\n"
        out += f"{pad}            super({d.name}.class, List.of(\n"
        rows = []
        for v in d.variants:
            req = [p.json_name for p in v.props if p.required]
            consts = [(p.json_name, p.const) for p in v.props if p.const is not None]
            req_s = ", ".join(java_string(r) for r in req)
            const_s = ", ".join(
                f"Map.entry({java_string(k)}, {java_string(c)})" for k, c in consts)
            rows.append(f"{pad}                    variant({self.ref(JType(decl=v))}.class, "
                        f"List.of({req_s}), Map.ofEntries({const_s}))")
        out += ",\n".join(rows) + "));\n"
        out += f"{pad}        }}\n{pad}    }}\n"
        out += self.children(d, indent + 4)
        out += f"{pad}}}\n"
        return out

    def render_class(self, d, indent):
        self.imports |= {
            "com.fasterxml.jackson.annotation.JsonInclude",
            "com.fasterxml.jackson.annotation.JsonProperty",
            "com.fasterxml.jackson.annotation.JsonPropertyOrder",
            "java.util.Objects",
        }
        pad = " " * indent
        p4 = pad + "    "
        out = javadoc(d.description, indent, ["@deprecated"] if d.deprecated else [])
        if d.deprecated:
            out += f"{pad}@Deprecated\n"
        out += self.schema_annotation(d, indent)
        out += f"{pad}@JsonInclude(JsonInclude.Include.NON_NULL)\n"
        if d.props:
            order = ", ".join(java_string(p.json_name) for p in d.props)
            out += f"{pad}@JsonPropertyOrder({{{order}}})\n"
        if d.interfaces:
            # Concrete variants must not inherit the union's deserializer.
            self.imports |= {"com.fasterxml.jackson.databind.JsonDeserializer",
                             "com.fasterxml.jackson.databind.annotation.JsonDeserialize"}
            out += f"{pad}@JsonDeserialize(using = JsonDeserializer.None.class)\n"
        impl = ""
        if d.interfaces:
            impl = " implements " + ", ".join(self.ref(JType(decl=i)) for i in d.interfaces)
        out += f"{pad}{self.modifiers(d, 'class')} class {d.name}{impl} {{\n"

        for p in d.props:
            t = self.ref(p.jtype)
            extra = []
            if p.required:
                extra.append("Required.")
            if p.default is not None:
                extra.append(f"Default: {{@code {json.dumps(p.default)}}}.")
            out += javadoc(p.description, indent + 4, [" ".join(extra)] if extra else [])
            if p.deprecated:
                out += f"{p4}@Deprecated\n"
            req = ", required = true" if p.required else ""
            out += f"{p4}@JsonProperty(value = {java_string(p.json_name)}{req})\n"
            init = (f" = {java_string(p.const)}"
                    if p.const is not None and p.required and t == "String" else "")
            out += f"{p4}private {t} {p.java_name}{init};\n\n"

        if d.extra is not None:
            self.imports |= {"com.fasterxml.jackson.annotation.JsonAnyGetter",
                             "com.fasterxml.jackson.annotation.JsonAnySetter",
                             "com.fasterxml.jackson.annotation.JsonIgnore",
                             "java.util.LinkedHashMap", "java.util.Map"}
            et = self.ref(d.extra)
            out += f"{p4}/** Properties not declared by the schema, preserved on round trips. */\n"
            out += f"{p4}@JsonIgnore\n{p4}private Map<String, {et}> additionalProperties = new LinkedHashMap<>();\n\n"

        for p in d.props:
            t = self.ref(p.jtype)
            cap = p.java_name[:1].upper() + p.java_name[1:]
            if cap.endswith("_"):
                cap = cap[:-1]
            dep = f"{p4}@Deprecated\n" if p.deprecated else ""
            out += javadoc(p.description, indent + 4, ["@return the value, or null if absent"])
            out += f"{dep}{p4}public {t} get{cap}() {{\n{p4}    return {p.java_name};\n{p4}}}\n\n"
            out += f"{dep}{p4}public void set{cap}({t} {p.java_name}) {{\n{p4}    this.{p.java_name} = {p.java_name};\n{p4}}}\n\n"
            out += f"{p4}/** Fluent setter for {{@code {p.json_name}}}. */\n"
            out += f"{dep}{p4}public {d.name} {p.java_name}({t} {p.java_name}) {{\n{p4}    this.{p.java_name} = {p.java_name};\n{p4}    return this;\n{p4}}}\n\n"

        if d.extra is not None:
            et = self.ref(d.extra)
            out += f"{p4}@JsonAnyGetter\n{p4}public Map<String, {et}> getAdditionalProperties() {{\n{p4}    return additionalProperties;\n{p4}}}\n\n"
            out += f"{p4}@JsonAnySetter\n{p4}public void setAdditionalProperty(String name, {et} value) {{\n{p4}    additionalProperties.put(name, value);\n{p4}}}\n\n"
            out += f"{p4}/** Fluent setter for a property not declared by the schema. */\n"
            out += f"{p4}public {d.name} additionalProperty(String name, {et} value) {{\n{p4}    additionalProperties.put(name, value);\n{p4}    return this;\n{p4}}}\n\n"

        fields = [p.java_name for p in d.props] + (["additionalProperties"] if d.extra is not None else [])
        out += f"{p4}@Override\n{p4}public boolean equals(Object o) {{\n"
        out += f"{p4}    if (this == o) {{\n{p4}        return true;\n{p4}    }}\n"
        out += f"{p4}    if (o == null || getClass() != o.getClass()) {{\n{p4}        return false;\n{p4}    }}\n"
        if fields:
            out += f"{p4}    {d.name} that = ({d.name}) o;\n"
            cmp = f"\n{p4}        && ".join(f"Objects.equals({f}, that.{f})" for f in fields)
            out += f"{p4}    return {cmp};\n"
        else:
            out += f"{p4}    return true;\n"
        out += f"{p4}}}\n\n"
        out += f"{p4}@Override\n{p4}public int hashCode() {{\n{p4}    return Objects.hash({', '.join(fields)});\n{p4}}}\n\n"
        parts = " + \", \"\n".join(f"{p4}        + \"{f}=\" + {f}" for f in fields) if fields else ""
        out += f"{p4}@Override\n{p4}public String toString() {{\n{p4}    return \"{d.name}{{\"\n"
        if parts:
            out += parts + "\n"
        out += f"{p4}        + \"}}\";\n{p4}}}\n"
        out += self.children(d, indent + 4)
        out += f"{pad}}}\n"
        return out


def main():
    if len(sys.argv) != 5:
        print(__doc__)
        sys.exit(2)
    schema_dir, out_root, base_package, schema_version = sys.argv[1:]
    gen = Generator(Schemas(schema_dir), base_package)
    gen.run()
    out_root = Path(out_root)
    count = 0
    written = set()
    for top in gen.tops:
        path = out_root / top.package.replace(".", "/") / f"{top.name}.java"
        if path in written:
            raise SystemExit(f"two top-level types map to {path}")
        written.add(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(Renderer(top, gen.tops, gen.s.docs).render(), encoding="utf-8")
        count += 1
    write_registry(out_root, base_package, schema_version)
    print(f"Generated {count + 1} Java files under {out_root}")


def write_registry(out_root, base_package, schema_version):
    for loc, target in ALIASES.items():
        key = target.file + ("#" + target.pointer if target.pointer else "")
        if key in REGISTRY:
            REGISTRY.setdefault(loc, REGISTRY[key])
    rows = ",\n".join(
        f"            Map.entry({java_string(loc)}, {fqn}.class)"
        for loc, fqn in sorted(REGISTRY.items()))
    body = f"""{HEADER}
package {base_package};

import java.util.Map;
import java.util.Optional;

/**
 * Index of every generated model by the UCP schema location it was generated from.
 *
 * <p>Locations are relative to {{@code https://ucp.dev/schemas/}} and may carry a JSON pointer
 * fragment, e.g. {{@code shopping/checkout.json}} or {{@code
 * shopping/catalog_search.json#/$defs/search_request}}.
 */
@SuppressWarnings("deprecation") // the index also lists models the schemas deprecate
public final class UcpModels {{
    /** The UCP specification release these models were generated from. */
    public static final String SCHEMA_VERSION = {java_string(schema_version)};

    private static final Map<String, Class<?>> MODELS = Map.ofEntries(
{rows});

    private UcpModels() {{}}

    /**
     * Looks up the model generated from a schema location.
     *
     * @param location the schema location
     * @return the model class, if one was generated for that location
     */
    public static Optional<Class<?>> forSchema(String location) {{
        return Optional.ofNullable(MODELS.get(location));
    }}

    /**
     * Returns every schema location and its model class.
     *
     * @return an unmodifiable map from schema location to model class
     */
    public static Map<String, Class<?>> all() {{
        return MODELS;
    }}
}}
"""
    path = out_root / base_package.replace(".", "/") / "UcpModels.java"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")


if __name__ == "__main__":
    main()
