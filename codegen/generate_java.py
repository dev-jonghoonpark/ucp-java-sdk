def words(name):
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", name)
    return [w for w in re.split(r"[^A-Za-z0-9]+", name) if w]


def pascal(name):
    out = "".join(w[:1].upper() + w[1:] for w in words(name))
    if not out:
        out = "Value"
    if out[0].isdigit():
        out = "_" + out
    return out


def camel(name):
    p = pascal(name)
    if p.startswith("_"):
        return p
    out = p[:1].lower() + p[1:]
    if out in JAVA_KEYWORDS:
        out += "_"
    return out


def constant(value):
    out = "_".join(w.upper() for w in words(str(value)))
    if not out:
        out = "EMPTY"
    if out[0].isdigit():
        out = "_" + out
    return out


def singular(name):
    p = pascal(name)
    for suffix, repl in (("ies", "y"), ("sses", "ss"), ("xes", "x"),
                         ("ches", "ch"), ("shes", "sh")):
        if p.endswith(suffix) and len(p) > len(suffix):
            return p[: -len(suffix)] + repl
    if p.endswith("s") and not p.endswith("ss") and len(p) > 1:
        return p[:-1]
    return p + "Item"


def java_string(s):
    return json.dumps(s, ensure_ascii=False)


def javadoc(text, indent, extra=()):
    lines = []
    if text:
        text = (text.replace("&", "&amp;").replace("<", "&lt;")
                .replace(">", "&gt;").replace("*/", "*&#47;")
                .replace("@", "&#64;").replace("\\u", "\\\\u"))
        lines.extend(text.strip().splitlines())
    for e in extra:
        if lines:
            lines.append("")
            if not e.startswith("@"):
                e = "<p>" + e
        lines.append(e)
    if not lines:
        return ""
    pad = " " * indent
    body = "\n".join(f"{pad} *{(' ' + ln) if ln.strip() else ''}" for ln in lines)
    return f"{pad}/**\n{body}\n{pad} */\n"


