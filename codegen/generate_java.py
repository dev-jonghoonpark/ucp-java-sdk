class Schemas:
    def __init__(self, root_dir):
        self.root = Path(root_dir).resolve()
        self.docs = {}
        for path in sorted(self.root.rglob("*.json")):
            rel = path.relative_to(self.root).as_posix()
            with path.open(encoding="utf-8") as f:
                self.docs[rel] = json.load(f)

    def resolve(self, ref, file):
        if "#" in ref:
            path, frag = ref.split("#", 1)
        else:
            path, frag = ref, ""
        if path:
            target = (Path(file).parent / path).as_posix()
            target = normalize_path(target)
        else:
            target = file
        if target not in self.docs:
            raise KeyError(f"unresolvable $ref {ref} from {file}")
        node = self.docs[target]
        pointer = frag or ""
        for part in [p for p in pointer.split("/") if p]:
            part = part.replace("~1", "/").replace("~0", "~")
            if isinstance(node, list):
                node = node[int(part)]
            else:
                node = node[part]
        return Loc(target, pointer, node)


def normalize_path(p):
    parts = []
    for seg in p.split("/"):
        if seg in ("", "."):
            continue
        if seg == "..":
            parts.pop()
        else:
            parts.append(seg)
    return "/".join(parts)


